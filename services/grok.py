# -*- coding: utf-8 -*-
"""
services/grok.py — общение с Grok API (xAI).
Тимур, тут мы берём ответы клиента из брифа и просим Grok:
1) найти главные боли клиента,
2) предложить, какая из твоих 3 услуг ему подходит,
3) составить короткое личное предложение в твоём стиле «по-братски».

Grok совместим с форматом OpenAI, поэтому работаем через обычный httpx.
Если ключа нет или сервис упал — бот не сломается, просто пропустит этот шаг.
"""

import httpx
from loguru import logger

from config import config

# === ГОТОВЫЙ ОПТИМИЗИРОВАННЫЙ ПРОМПТ ДЛЯ GROK ===
# Тимур, это «характер» твоего ассистента. Меняй смело под себя.
SYSTEM_PROMPT = """Ты — личный ассистент Тимура, предпринимателя из Новороссии.
Тимур работает ОДИН, без команды и менеджеров — это его сильная сторона: всё лично, под контролем, по-братски.

Тимур делает 3 услуги:
1. ИИ Автоматизация — 35 000₽
2. Медиа и контент — 25 000₽
3. Продающий сайт + реклама — 45 000₽

Условия работы:
- Оплата 50/50: половина предоплата, половина по результату.
- Приём оплаты: Сбер / Тинькофф.
- Связь: Telegram / WhatsApp / Авито.
- Аудитория: малый бизнес Новороссии — салоны, магазины, услуги, общепит.
- Тон: личный, тёплый, доверительный, на «ты», по-братски. Без корпоративного пафоса и канцелярита.

ТВОЯ ЗАДАЧА: проанализировать ответы клиента из брифа и вернуть ответ СТРОГО в таком формате:

🔥 ГЛАВНЫЕ БОЛИ:
- (2-3 пункта, конкретно, словами клиента)

💡 ЧТО ПРЕДЛАГАЮ:
- (1-2 услуги из списка выше, с ценой и коротким объяснением, ПОЧЕМУ именно это решит его боль)

🤝 ЛИЧНОЕ СООБЩЕНИЕ КЛИЕНТУ:
(3-4 предложения от лица Тимура: тёпло, по-братски, обязательно упомяни, что работаешь сам и лично доведёшь до результата, и про честную схему 50/50. Заверши приглашением списаться.)

Пиши по-русски, живо, без воды. Не выдумывай услуги и цены, которых нет в списке."""


async def analyze_brief(answers: dict) -> str:
    """
    Отправляем ответы клиента в Grok и получаем анализ + предложение.
    Если Grok выключен или произошла ошибка — возвращаем пустую строку
    (бот продолжит работу без анализа).
    """
    if not config.grok_enabled:
        logger.warning("⚠️  Grok отключён (нет GROK_API_KEY) — пропускаем анализ")
        return ""

    # Собираем ответы клиента в читаемый текст для модели
    brief_text = "\n".join(f"- {key}: {value}" for key, value in answers.items())
    user_message = f"Вот ответы клиента из брифа:\n{brief_text}\n\nПроанализируй по инструкции."

    payload = {
        "model": config.grok_model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_message},
        ],
        "temperature": 0.7,
        "stream": False,
    }
    headers = {
        "Authorization": f"Bearer {config.grok_api_key}",
        "Content-Type": "application/json",
    }

    try:
        async with httpx.AsyncClient(timeout=60) as client:
            response = await client.post(
                f"{config.grok_base_url}/chat/completions",
                json=payload,
                headers=headers,
            )
            response.raise_for_status()
            data = response.json()
            result = data["choices"][0]["message"]["content"].strip()
            logger.info("🤖 Grok успешно проанализировал заявку")
            return result
    except httpx.HTTPStatusError as e:
        logger.error(f"❌ Grok вернул ошибку {e.response.status_code}: {e.response.text[:200]}")
    except Exception as e:
        logger.error(f"❌ Не смог достучаться до Grok: {e}")

    return ""
